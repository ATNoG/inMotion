@dataclass
class DatasetVersion:
    """One recorded version of one dataset file."""

    id: str
    file: str
    role: str
    status: str
    label_audit: str
    validity_note: str = ""
    lineage: dict[str, Any] = field(default_factory=dict)
    # Measured fields, filled by build_manifest.
    sha256: str = ""
    rows: int = 0
    columns: list[str] = field(default_factory=list)
    classes: list[str] = field(default_factory=list)
    class_counts: dict[str, int] = field(default_factory=dict)
    devices: int = 0
    synthetic: bool = False
    size_bytes: int = 0
    first_commit: str | None = None
    first_commit_date: str | None = None

    @property
    def path(self) -> Path:
        return REPO_ROOT / self.file

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "file": self.file,
            "role": self.role,
            "status": self.status,
            "label_audit": self.label_audit,
            "validity_note": self.validity_note,
            "lineage": self.lineage,
            "sha256": self.sha256,
            "rows": self.rows,
            "columns": self.columns,
            "classes": self.classes,
            "class_counts": self.class_counts,
            "devices": self.devices,
            "synthetic": self.synthetic,
            "size_bytes": self.size_bytes,
            "first_commit": self.first_commit,
            "first_commit_date": self.first_commit_date,
        }


