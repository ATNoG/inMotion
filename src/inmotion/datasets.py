def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _first_commit(path: Path) -> tuple[str | None, str | None]:
    """The commit that first added ``path``, and its author date."""
    try:
        out = subprocess.run(
            [
                "git",
                "log",
                "--diff-filter=A",
                "--format=%H|%ad",
                "--date=short",
                "--",
                str(path.name),
            ],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=15,
            check=True,
        )
        lines = [ln for ln in out.stdout.strip().splitlines() if ln]
        if not lines:
            return None, None
        sha, _, date = lines[-1].partition("|")
        return sha, date or None
    except Exception:
        return None, None


def measure(version: DatasetVersion) -> DatasetVersion:
    """Fill in the measured fields from the file on disk."""
    path = version.path
    if not path.exists():
        raise FileNotFoundError(f"{version.id}: {path} does not exist")

    frame = pd.read_csv(path)
    version.sha256 = _sha256(path)
    version.size_bytes = path.stat().st_size
    version.rows = len(frame)
    version.columns = list(frame.columns)
    if "label" in frame.columns:
        counts = frame["label"].astype(str).value_counts()
        version.class_counts = {str(k): int(v) for k, v in counts.items()}
        version.classes = sorted(version.class_counts)
    version.synthetic = "synthetic" in frame.columns
    if "mac" in frame.columns:
        version.devices = int(frame["mac"].nunique())
    version.first_commit, version.first_commit_date = _first_commit(path)
    return version


def build_manifest() -> dict[str, Any]:
    """Regenerate the whole manifest, measuring every curated version."""
    versions = [measure(v) for v in CURATED]
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "canonical": CANONICAL_ID,
        "note": (
            "Datasets are tracked in git; this manifest records checksums, "
            "lineage and label provenance. Regenerate the measured fields with "
            "`inmotion datasets manifest --write`."
        ),
        "datasets": [v.to_dict() for v in versions],
    }


def write_manifest(path: Path | None = None) -> Path:
    path = path or MANIFEST_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(build_manifest(), indent=2) + "\n")
    return path


def load_manifest(path: Path | None = None) -> dict[str, Any] | None:
    """Read the manifest, or None when it has not been generated yet."""
    path = path or MANIFEST_PATH
    if not path.exists():
        return None
    return json.loads(path.read_text())


def verify() -> list[tuple[str, str]]:
    """Check every recorded dataset against its checksum and row count.

    Returns a list of ``(id, problem)``; empty means everything matches.
    """
    manifest = load_manifest()
    if manifest is None:
        return [
            ("<manifest>", f"missing {MANIFEST_PATH}; run `inmotion datasets manifest --write`")
        ]

    problems: list[tuple[str, str]] = []
    for entry in manifest["datasets"]:
        path = REPO_ROOT / entry["file"]
        if not path.exists():
            problems.append((entry["id"], f"missing file {entry['file']}"))
            continue
        actual = _sha256(path)
        if actual != entry["sha256"]:
            problems.append(
                (
                    entry["id"],
                    f"checksum changed: manifest {entry['sha256'][:12]}, file {actual[:12]}",
                )
            )
            continue
        rows = len(pd.read_csv(path))
        if rows != entry["rows"]:
            problems.append((entry["id"], f"row count changed: {entry['rows']} -> {rows}"))
    return problems


def resolve(identifier: str) -> DatasetVersion:
    """Find a dataset version by id or file name."""
    manifest = load_manifest()
    if manifest is None:
        raise FileNotFoundError("no dataset manifest; run `inmotion datasets manifest --write`")
    for entry in manifest["datasets"]:
        if identifier in (entry["id"], entry["file"]):
            return DatasetVersion(
                **{k: v for k, v in entry.items() if k in DatasetVersion.__dataclass_fields__}
            )
    known = ", ".join(e["id"] for e in manifest["datasets"])
    raise KeyError(f"no dataset {identifier!r}; known: {known}")


def canonical() -> DatasetVersion:
    """The dataset new training runs should use."""
    return resolve(CANONICAL_ID)
