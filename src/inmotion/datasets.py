"""Dataset version registry.

The datasets are committed to git, so their history *is* the version history.
What git cannot tell you is which version is safe to train on: earlier
collections were assembled with different device pools, and the project owner
reports that older versions carry incorrect class labels. That knowledge is
recorded here, next to checksums that prove a file has not silently changed.

Two kinds of information are kept apart on purpose:

* **Measured** — sha256, row count, class counts, device count, size, and the
  commit that first added the file. Regenerated by :func:`build_manifest`, so it
  cannot drift.
* **Curated** — role, lineage, status and the label audit. Written by hand,
  because it is project knowledge rather than something derivable from the file.

`:func:`verify` re-checks the measured side, so a dataset that changed under
git's feet (a re-export written over the same path) is caught.
"""

